"""fable_40fps.py XBE [OUT]: mods/4D5300D1.1/40fps/mod.txt from Fable: The
Lost Chapters' default.xbe (4D5300D1, version 1), its bytes checked first.

Fable steps its logic 15 times a second ([0x912BD8]) and draws each frame
between two steps (0x1F3730, 0x1F3EC0): its frame rate is free of its logic.
What caps it is the presentation interval. 0x3F700 (called with the area's
target frame rate) waits N = ceil(R / fps) vblanks a frame, 1-3, "or
immediately" when a frame is late, R being the display object's refresh
([obj+0x1B8], from D3D's display mode: 60); N is kept at [obj+0x1C0] and the
frame period N / R at [obj+0x1C4], which the game clock (0x1F36C0) uses to
predict when a frame shows. At 60 Hz the cap is 60, 30 or 20 fps.

With the vblank at 120 Hz (refresh: 120) and R doubled where the display
object takes it (0x3F05D and 0x3F503: call the cave, which loads the mode's
refresh, doubles it and does the cvtsi2ss the call replaced), N = 3 for any
target of 40 fps or less: a frame every third vblank, 40 a second, and the
frame period 3/120 s. Fixed intervals (loading screens: 2 vblanks) run twice
as fast in frames, not in time.
"""
import struct
import sys

CAVE = 0x3F881          # int3 padding after 0x3F820 (15 bytes)
CAVE_CODE = bytes.fromhex('8B44241C 01C0 F30F2A85C0010000 C3')   # mov eax,[esp+1C]; add eax,eax;
                                                                 # cvtsi2ss xmm0,[ebp+1C0]; ret
SITES = (0x3F05D, 0x3F503)
SITE_OLD = bytes.fromhex('8B442418 F30F2A85C0010000')               # mov eax,[esp+18]; cvtsi2ss xmm0,[ebp+1C0]

HEADER = """name: 40 fps
description: The game at 40 frames a second (on a 120 Hz screen) instead of 20 or 30, at its normal speed: its logic still steps 15 times a second and every frame is drawn between two steps, as the game does. A frame the device doesn't finish in time shows as soon as it is done. Keep the frame rate capped (Settings: Uncap frame rate off). Use it instead of the 60 fps mod, not with it.
author: hakuX
refresh: 120

# Generated by tools/mods/fable_40fps.py from default.xbe (4D5300D1, v1).
# Fable's logic runs at 15 steps a second and it draws between them; its cap
# is the presentation interval: 0x3F700 waits N = ceil(R / fps) vblanks a
# frame (1-3, or at once if late), R the refresh the display object keeps
# ([obj+0x1B8], 60), and its frame period N / R ([obj+0x1C4]) feeds the game
# clock (0x1F36C0). With the vblank at 120 Hz and R doubled where the object
# takes it (0x3F05D, 0x3F503 call the cave at 0x3F881: the mode's refresh
# times 2, then the cvtsi2ss the call replaced), N is 3 for targets of 40 fps
# or less: 40 frames a second, a period of 1/40 s.
[default.xbe]
"""


def main():
    d = open(sys.argv[1], 'rb').read()
    base, = struct.unpack_from('<I', d, 0x104)
    cert, = struct.unpack_from('<I', d, 0x118)
    title, = struct.unpack_from('<I', d, cert - base + 8)
    version, = struct.unpack_from('<I', d, cert - base + 0xAC)
    assert (title, version) == (0x4D5300D1, 1), 'not Fable TLC 4D5300D1 v1: %08X v%u' % (title, version)
    nsec, secva = struct.unpack_from('<II', d, 0x11C)

    def at(va, n):
        for i in range(nsec):
            _, sva, _, raw, rsize = struct.unpack_from('<IIIII', d, secva - base + i * 0x38)
            if sva <= va < sva + rsize:
                return d[raw + va - sva:raw + va - sva + n]
        raise ValueError(hex(va))

    def hx(b):
        return ' '.join('%02X' % x for x in b)

    lines = []
    assert at(CAVE, len(CAVE_CODE)) == b'\xCC' * len(CAVE_CODE), 'cave not free'
    lines.append('0x%08X: %s -> %s' % (CAVE, hx(at(CAVE, len(CAVE_CODE))), hx(CAVE_CODE)))
    for va in SITES:
        assert at(va, len(SITE_OLD)) == SITE_OLD, hex(va)
        new = b'\xE8' + struct.pack('<i', CAVE - (va + 5)) + b'\x90' * (len(SITE_OLD) - 5)
        lines.append('0x%08X: %s -> %s' % (va, hx(SITE_OLD), hx(new)))
    text = HEADER + '\n'.join(lines) + '\n'
    if len(sys.argv) > 2:
        with open(sys.argv[2], 'w', newline='\n') as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == '__main__':
    main()
